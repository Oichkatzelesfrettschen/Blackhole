// Falsifier: any ZAMO, static, orbiting, or boosted tetrad failing
// g(e_a, e_b) = eta_ab by more than 1e-12 at (r = 6, a = 0.9) or (r = 3, a = 0).
// r = 3 at a = 0 is the photon sphere, so a generic sub-luminal boost stands in
// for the orbiter there.
TEST(KerrObserver, TetradsAreOrthonormal) {
  const double x6 = 5.0;
  const ko::Tetrad zamo6 = ko::zamoTetrad(0.1, x6);
  EXPECT_LT(orthonormalityError(zamo6), 1e-12);
  EXPECT_LT(orthonormalityError(ko::orbitingTetrad(0.1, x6, OrbitSense::Prograde)), 1e-12);
  EXPECT_LT(orthonormalityError(ko::orbitingTetrad(0.1, x6, OrbitSense::Retrograde)), 1e-12);
  EXPECT_LT(orthonormalityError(ko::boostedTetrad(
                zamo6, ko::Vec3{0.0, 0.0, ko::staticObserverVelocity(zamo6.frame)})),
            1e-12);
  EXPECT_LT(orthonormalityError(ko::boostedTetrad(zamo6, ko::Vec3{0.3, -0.2, 0.4})), 1e-12);

  const ko::Tetrad zamo3 = ko::zamoTetrad(1.0, 2.0);
  EXPECT_LT(orthonormalityError(zamo3), 1e-12);
  EXPECT_FALSE(ko::circularOrbit(1.0, 2.0, OrbitSense::Prograde).exists);
  EXPECT_LT(orthonormalityError(ko::boostedTetrad(zamo3, ko::Vec3{0.3, -0.2, 0.4})), 1e-12);
  // A boost of a boost composes: still orthonormal.
  EXPECT_LT(orthonormalityError(ko::boostedTetrad(ko::boostedTetrad(zamo3, ko::Vec3{0.0, 0.0, 0.6}),
                                                  ko::Vec3{0.5, 0.0, -0.3})),
            1e-12);
}

// Falsifier: the Miller orbiter's tetrad failing orthonormality beyond
// 64 kappa DBL_EPSILON with kappa = 1/alpha^2. The textbook contraction sums
// O(1/alpha^2) terms to O(1), so kappa bounds the roundoff any correct tetrad
// shows; a wrong leg misses by O(1).
TEST(KerrObserver, MillerTetradIsOrthonormalWithinConditioning) {
  const double xIsco = ko::iscoOffset(K_CANON_EPSILON, OrbitSense::Prograde);
  const ko::Tetrad miller = ko::orbitingTetrad(K_CANON_EPSILON, xIsco, OrbitSense::Prograde);
  const double kappa = 1.0 / (miller.frame.alpha * miller.frame.alpha);
  EXPECT_LT(orthonormalityError(miller), 64.0 * kappa * DBL_EPSILON);
  EXPECT_LT(orthonormalityError(ko::zamoTetrad(K_CANON_EPSILON, xIsco)),
            64.0 * kappa * DBL_EPSILON);
}

// Falsifier: the orbiter tetrad's time leg u^t = gamma/alpha disagreeing with
