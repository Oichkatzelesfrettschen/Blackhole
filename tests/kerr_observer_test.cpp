// Falsifier: the KerrTimeField built from the canon deficit reporting a delay
// between Miller's orbit and the far bands off quadrature by more than 1e-9
// relative after the cm round trip, or a horizon anywhere but M (1 + h).
TEST(KerrObserver, KerrTimeFieldDelegatesDelayAtCanonSpin) {
  const double massG = 1.0e8 * K_SOLAR_MASS_G;
  const game::KerrTimeField field(massG, game::SpinDeficit{.epsilon = K_CANON_EPSILON});
  const double mCm = field.gravitationalRadiusCm();
  EXPECT_DOUBLE_EQ(field.spinDeficit(), K_CANON_EPSILON);
  expectRelative((field.outerHorizonCm() / mCm) - 1.0, ko::horizonOffset(K_CANON_EPSILON), 1e-6,
                 "horizon offset");
  for (const DelayRow &row : K_DELAYS) {
    if (row.epsilon != K_CANON_EPSILON) {
      continue;
    }
    const double delaySec = field.signalDelaySec(mCm * (1.0 + row.x1), mCm * (1.0 + row.x2));
    expectRelative(delaySec * 2.99792458e10 / mCm, row.delayM, 1e-9, "canon field delay");
  }
}

