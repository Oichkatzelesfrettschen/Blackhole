void expectRelative(double actual, double expected, double tolerance, const char *what) {
  if (expected == 0.0) {
    EXPECT_NEAR(actual, 0.0, tolerance) << what;
    return;
  }
  EXPECT_NEAR(actual / expected, 1.0, tolerance)
      << what << " actual=" << actual << " expected=" << expected;
}

/** Textbook equatorial Boyer-Lindquist metric g_{mu nu} in (a, r), M = 1. */
std::array<ko::Vec4, 4> textbookMetric(double spin, double r) {
  const double delta = (r * r) - (2.0 * r) + (spin * spin);
  std::array<ko::Vec4, 4> g{};
  g.at(0).at(0) = -(1.0 - (2.0 / r));
  g.at(0).at(3) = -2.0 * spin / r;
  g.at(3).at(0) = g.at(0).at(3);
  g.at(3).at(3) = (r * r) + (spin * spin) + (2.0 * spin * spin / r);
  g.at(1).at(1) = r * r / delta;
  g.at(2).at(2) = r * r;
  return g;
}

double contract(const std::array<ko::Vec4, 4> &g, const ko::Vec4 &u, const ko::Vec4 &v) {
  double sum = 0.0;
  for (std::size_t mu = 0; mu < 4; ++mu) {
    for (std::size_t nu = 0; nu < 4; ++nu) {
      sum += g.at(mu).at(nu) * u.at(mu) * v.at(nu);
    }
  }
  return sum;
}

/** Largest |g(e_a, e_b) - eta_ab| over the tetrad's legs, textbook metric. */
double orthonormalityError(const ko::Tetrad &tetrad) {
  const auto g = textbookMetric(tetrad.frame.spin, tetrad.frame.r);
  double worst = 0.0;
  for (std::size_t a = 0; a < 4; ++a) {
    for (std::size_t b = 0; b < 4; ++b) {
      double eta = 0.0;
      if (a == b) {
        eta = a == 0 ? -1.0 : 1.0;
      }
      const double value = contract(g, ko::legComponents(tetrad, a), ko::legComponents(tetrad, b));
      worst = std::fmax(worst, std::fabs(value - eta));
    }
  }
  return worst;
}

/** BPT closed-form u^t and Omega for a circular orbit in (a, r), M = 1. */
struct TextbookOrbit {
  double timeComponent;
  double angularVelocity;
};

TextbookOrbit textbookOrbit(double spin, double r, double sense) {
  const double r32 = r * std::sqrt(r);
  const double radicand = r32 - (3.0 * std::sqrt(r)) + (2.0 * sense * spin);
  return {.timeComponent = (r32 + (sense * spin)) / (std::pow(r, 0.75) * std::sqrt(radicand)),
          .angularVelocity = sense / (r32 + (sense * spin))};
}

/** Direction `index` of a `count`-point Fibonacci lattice on the unit sphere:
 *  deterministic on every standard library and uniform to O(1/count). */
ko::Vec3 latticeDirection(int index, int count) {
  const double z = 1.0 - ((2.0 * (static_cast<double>(index) + 0.5)) / static_cast<double>(count));
  const double ring = std::sqrt(1.0 - (z * z));
  const double goldenAngle = std::numbers::pi * (3.0 - std::sqrt(5.0));
  const double phi = goldenAngle * static_cast<double>(index);
  return {ring * std::cos(phi), z, ring * std::sin(phi)};
}

