// Falsifier: a lapse, frame-drag rate, cylindrical radius, orbital clock, or
// orbital angular velocity off the 50-digit textbook value by more than 1e-12
// relative, or an orbit reported where none is timelike (the r = 3M photon
// sphere at a = 0 among them) or missing where one is.
TEST(KerrObserver, FrameAndOrbitsMatchReference) {
  for (const PointRow &row : K_POINTS) {
    const ko::EquatorialFrame frame = ko::equatorialFrame(row.epsilon, row.x);
    expectRelative(frame.alpha, row.alpha, 1e-12, "alpha");
    expectRelative(frame.omega, row.omega, 1e-12, "omega");
    expectRelative(frame.varpi, row.varpi, 1e-12, "varpi");
    const ko::CircularOrbit pro = ko::circularOrbit(row.epsilon, row.x, OrbitSense::Prograde);
    const ko::CircularOrbit retro = ko::circularOrbit(row.epsilon, row.x, OrbitSense::Retrograde);
    EXPECT_EQ(pro.exists, row.ratePro > 0.0) << "prograde existence at x=" << row.x;
    EXPECT_EQ(retro.exists, row.rateRetro > 0.0) << "retrograde existence at x=" << row.x;
    if (pro.exists) {
      expectRelative(pro.properTimeRate, row.ratePro, 1e-12, "prograde rate");
      expectRelative(pro.angularVelocity, row.omegaPro, 1e-12, "prograde Omega");
    }
    if (retro.exists) {
      expectRelative(retro.properTimeRate, row.rateRetro, 1e-12, "retrograde rate");
      expectRelative(retro.angularVelocity, row.omegaRetro, 1e-12, "retrograde Omega");
    }
  }
}

